GLYPHS[" "] = ("00000",) * HEIGHT


def glyph_columns(rows: tuple[str, ...]) -> bytes:
    """One glyph in the wire's column-major, MSB-first packing."""
    per_column = (len(rows) + 7) // 8
    out = bytearray()
    for x in range(len(rows[0])):
        bits = 0
        for y, row in enumerate(rows):
            if row[x] == "1":
                bits |= 1 << (per_column * 8 - 1 - y)
        out.extend(bits.to_bytes(per_column, "big"))
    return bytes(out)


def digit_table(square: bool = False) -> bytes:
    """The ten-glyph table a Clock, Countdown or Stopwatch expects, for
    num_width=WIDTH, num_height=HEIGHT."""
    digits = SQUARE_DIGITS if square else GLYPHS
    return b"".join(glyph_columns(digits[d]) for d in "0123456789")


def colon(width: int = 1) -> bytes:
    """The ':' glyph's one lit column, then blank ones up to `width`,
    for a Clock's separator field -- a whole 5-wide cell would leave
    the colon floating in a gap.

    `width` must be the separator field's own width. The sign draws
    that many columns whatever length the bitmap says it is, reading
    on into the next field's bytes when the bitmap is short: a 1-column
    colon in a 2-column field lit a stray line beside it, made of the
    minute field's colour."""
    lit = tuple(row[2] for row in GLYPHS[":"])
    return glyph_columns(tuple(dot + "0" * (width - 1) for dot in lit))


def render(text: str, color: tuple[int, int, int] = (255, 255, 255),
           spacing: int = 1) -> Image.Image:
    """`text` as an image HEIGHT rows tall, one blank column between
    characters, ready for image_to_pixel_data. Anything the font
    doesn't have renders as a space."""
    width = max(0, len(text) * (WIDTH + spacing) - spacing)
    image = Image.new("RGB", (width, HEIGHT), (0, 0, 0))
    for index, char in enumerate(text):
        rows = GLYPHS.get(char, GLYPHS[" "])
        left = index * (WIDTH + spacing)
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "1":
                    image.putpixel((left + x, y), color)
    return image
